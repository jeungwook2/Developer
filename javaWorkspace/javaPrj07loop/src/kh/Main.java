package kh;

public class Main {

	public static void main(String[] args) {
		
		System.out.println("===== 반복문 =====");
	
		/*
		 * <while>
		 * 문법 : while(조건식){실행내용}
		 * 조건식이 true 이면, 실행내용 실행 O
		 * 조건식이 false 이면, 실행내용 실행 X
		 * 실행내용이 끝나면, 조건식으로 다시 돌아옴
		 * 
		 */
		
		int i = 0;
		while(i<10) {
			System.out.println("안녕");
			i++;
		}
		
	}

}
