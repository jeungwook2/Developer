CREATE SEQUENCE SEQ_BOOK; NOCACHE NOCYCLE;

DROP TABLE BOOK CASCADE CONSTRAINT;

CREATE TABLE BOOK(
    NO NUMBER PRIMARY KEY,
    TITLE VARCHAR2(100),
    WRITER VARCHAR2(100),
    PRICE NUMBER,
    PUBLISHED_DATE   TIMESTAMP DEFAULT SYSDATE,
    DEL_YN   CHAR(1) DEFAULT 'N' CHECK(DEL_YN IN ('Y','N')) 
);


